function language(locale) {
  var code = String(locale || "").trim().toLowerCase().split(/[-_.@]/)[0]
  return code === "es" || code === "pt" ? code : "en"
}

function t(locale, source, values) {
  var lang = language(locale)
  var fallback = Object.prototype.hasOwnProperty.call(messages.en, source) ? messages.en[source] : source
  var text = Object.prototype.hasOwnProperty.call(messages[lang], source) ? messages[lang][source] : fallback
  return String(text).replace(/\{(\w+)\}/g, function(match, key) {
    return values && Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  })
}

function regionLabel(locale, label) {
  var lang = language(locale)
  return String(label).split(" · ").map(function(part) {
    return Object.prototype.hasOwnProperty.call(countries[lang], part) ? countries[lang][part] : t(lang, part)
  }).join(" · ")
}

function regionEntries(locale, entries) {
  var result = entries.map(function(entry) {
    var localized = {}
    for (var key in entry) localized[key] = entry[key]
    localized.searchLabel = entry.label
    localized.label = regionLabel(locale, entry.label)
    return localized
  })
  result.sort(function(a, b) {
    if (a.auto !== b.auto) return a.auto ? -1 : 1
    if (a.dedicated !== b.dedicated) return a.dedicated ? -1 : 1
    return a.label.localeCompare(b.label)
  })
  return result
}
